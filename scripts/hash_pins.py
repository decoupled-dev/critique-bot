"""Write a hash-pinned requirements file for a CI tool (maintainers; needs PyPI).

    python scripts/hash_pins.py .github/requirements/bandit.txt bandit==1.9.4

Resolves the tool and everything it pulls in for the CI runner (CPython 3.12, Linux x64)
with ``pip install --dry-run --report``, then lists every file PyPI has for each exact
version with its sha256, so ``pip install --require-hashes --no-deps -r <file>`` installs
nothing that was not reviewed here. Rerun it when a tool's pin changes, and commit the file.
"""

from __future__ import annotations

import json
import subprocess  # nosec B404 - runs pip, a fixed argv
import sys
import tempfile
import urllib.request
from pathlib import Path

PLATFORM = ("--python-version", "3.12", "--implementation", "cp", "--platform", "manylinux_2_17_x86_64",
            "--platform", "manylinux2014_x86_64", "--platform", "manylinux_2_28_x86_64", "--only-binary=:all:")


def resolve(tops: list[str]) -> list[tuple[str, str]]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        subprocess.run(  # nosec B603 - fixed argv, the tool names come from the maintainer
            [sys.executable, "-m", "pip", "install", "-q", "--dry-run", "--ignore-installed", "--report", str(report),
             "--target", str(Path(tmp) / "t"), *PLATFORM, *tops],
            check=True,
        )
        data = json.loads(report.read_text(encoding="utf-8"))
    return sorted({(item["metadata"]["name"], item["metadata"]["version"]) for item in data["install"]},
                  key=lambda pair: pair[0].lower())


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:  # nosec B310 - a fixed https URL
        data = json.load(response)
    return sorted({item["digests"]["sha256"] for item in data["urls"]})


def main(argv: list[str]) -> int:
    # pip applies --python-version to wheel tags only; environment markers such as
    # python_version < "3.13" are evaluated against the interpreter running pip. Run this
    # with the CI's Python, or dependencies behind such markers go missing (typing_extensions).
    if sys.version_info[:2] != (3, 12):
        print("run this with Python 3.12 (the version CI installs the tools with): python3.12 scripts/hash_pins.py ...",
              file=sys.stderr)
        return 2
    if len(argv) < 2:
        print(__doc__)
        return 2
    out, tops = Path(argv[0]), argv[1:]
    lines = ["# SPDX-License-Identifier: Apache-2.0",
             "# Generated by scripts/hash_pins.py for " + " ".join(tops) + " (CPython 3.12, Linux x64).",
             "# Install with: pip install --require-hashes --no-deps -r <this file>"]
    for name, version in resolve(tops):
        pins = " \\\n    ".join(f"--hash=sha256:{digest}" for digest in hashes(name, version))
        lines.append(f"{name}=={version} \\\n    {pins}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
