#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the license of every third-party package crit ships.

Offline: it reads the metadata of the packages installed in the Python environment that
runs it (run it with crit's own environment) and the desktop app's node_modules. Run it
again after changing constraints.txt or the desktop app's dependencies, and commit the
result.

    .venv/bin/python scripts/third_party_notices.py
"""

from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "THIRD_PARTY_NOTICES.md"
LICENSE_NAMES = re.compile(r"(?i)^(licen[cs]e|copying|notice)(\.[a-z]+)?$|^licen[cs]e[-_.]")

#: Code from npm that ships inside the desktop app (everything else there is build-time only).
DESKTOP_SHIPPED = {
    "@xterm/xterm": "renderer/vendor/xterm.js and xterm.css (terminal view)",
    "electron": "the app runtime (Chromium and Node.js; Chromium's own notices ship as LICENSES.chromium.html)",
}


def pinned_packages() -> list[str]:
    names = []
    for line in (REPO / "constraints.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if "==" in line:
            names.append(line.split("==", 1)[0].strip())
    return names


def license_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return ", ".join(classifiers)
    text = (meta.get("License") or "").strip()
    return text if text and len(text) < 80 else "see license text"


def license_texts(dist: metadata.Distribution) -> list[str]:
    texts = []
    for file in dist.files or []:
        if LICENSE_NAMES.match(Path(str(file)).name):
            try:
                texts.append(Path(dist.locate_file(file)).read_text(encoding="utf-8", errors="replace").strip())
            except OSError:
                continue
    return texts


def python_section() -> list[str]:
    lines = ["## Python packages", "", "Pinned in `constraints.txt` and installed with crit.", ""]
    missing = []
    for name in pinned_packages():
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            missing.append(name)
            continue
        url = dist.metadata.get("Home-page") or next(
            (u.split(",", 1)[-1].strip() for u in dist.metadata.get_all("Project-URL") or []), ""
        )
        lines += [f"### {dist.metadata['Name']} {dist.version}", "", f"License: {license_of(dist)}  "]
        if url:
            lines.append(f"Source: {url}")
        lines.append("")
        for text in license_texts(dist):
            lines += ["```", text, "```", ""]
    if missing:
        sys.exit(f"not installed in this environment: {', '.join(missing)}; run with crit's own Python")
    return lines


def desktop_section() -> list[str]:
    modules = REPO / "desktop" / "node_modules"
    lines = ["## Desktop app", "", "npm packages that ship inside the app.", ""]
    for name, what in DESKTOP_SHIPPED.items():
        package = modules / name / "package.json"
        if not package.is_file():
            sys.exit(f"{package} is missing; run npm ci in desktop/ first")
        info = json.loads(package.read_text(encoding="utf-8"))
        lines += [f"### {name} {info.get('version', '')}", "", f"License: {info.get('license', '?')}  ", f"Ships as: {what}", ""]
        for candidate in ("LICENSE", "LICENSE.md", "LICENSE.txt"):
            path = modules / name / candidate
            if path.is_file():
                lines += ["```", path.read_text(encoding="utf-8", errors="replace").strip(), "```", ""]
                break
    return lines


def main() -> int:
    parts = [
        "# Third-party notices",
        "",
        "crit (critique-bot) is licensed under the Apache License 2.0 (see LICENSE and NOTICE).",
        "It ships the third-party software below. Generated by `scripts/third_party_notices.py`;",
        "do not edit by hand.",
        "",
        "Build-time tools (TypeScript, the VS Code extension packager, electron-builder, test",
        "libraries) are not shipped and are not listed.",
        "",
    ]
    parts += python_section() + desktop_section()
    OUT.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
