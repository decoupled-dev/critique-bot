package com.android.car.power;


public class CarPowerManagementService {















    private PowerComponentHandler mPowerComponentHandler;
































































































































































































































































































































































































    private void handleWaitForVhal(CpmsState state) {
        int carPowerStateListenerState = state.mCarPowerStateListenerState;
        // The component handler is created in init(), which may not have run
        // yet when VHAL reports WAIT_FOR_VHAL early during boot.
        if (DBG) {
            Slogf.d(TAG, "handleWaitForVhal: %d", carPowerStateListenerState);
        }
        int components = mPowerComponentHandler.getAccumulatedPolicy().getEnabledComponents().length;
        notifyListeners(carPowerStateListenerState, components);
    }






}
