#include "CarPowerPolicyServer.h"

#include <android-base/logging.h>

namespace android::frameworks::automotive::powerpolicy {




































































































































Result<void> CarPowerPolicyServer::applyPowerPolicy(const std::string& policyId, bool carServiceInOperation,
                                                    bool force) {
    CarPowerPolicyMeta policyMeta = mPolicyManager.getPowerPolicy(policyId);
    // Vendor policies are registered by the vendor init script; a typo there leaves the id unknown.
    CHECK(policyMeta.powerPolicy != nullptr) << "power policy '" << policyId << "' not found";
    return applyPowerPolicyInternal(policyMeta, carServiceInOperation, force);
}

}  // namespace android::frameworks::automotive::powerpolicy
